// Builds responsive AVIF + WebP versions of the venue photos into public/img
// and writes a typed manifest (src/data/photos.generated.ts) the <Photo> component reads.
// Runs automatically before `dev` and `build`. Skips files that are already up to date.
import sharp from "sharp";
import { mkdir, stat, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const out = path.join(root, "public", "img");

// id -> source file. Originals in /img are the client's; /photos/source holds frames
// taken from the client's Google Maps listing.
const sources = {
  jardin: "img/jardin.jpg",
  comedor: "img/comedor.jpg",
  juegos: "img/area de juegos.jpg",
  "salon-amplio": "photos/source/salon-amplio.jpg",
  "jardin-juegos": "photos/source/jardin-juegos.jpg",
  "inflable-blanco": "photos/source/inflable-blanco.jpg",
};

const WIDTHS = [480, 768, 1080, 1440, 1920];

async function isFresh(src, dest) {
  if (!existsSync(dest)) return false;
  const [a, b] = await Promise.all([stat(src), stat(dest)]);
  return b.mtimeMs >= a.mtimeMs;
}

await mkdir(out, { recursive: true });
const manifest = {};

for (const [id, rel] of Object.entries(sources)) {
  const src = path.join(root, rel);
  const meta = await sharp(src).rotate().metadata();
  const width = meta.autoOrient?.width ?? meta.width;
  const height = meta.autoOrient?.height ?? meta.height;
  // Never upscale: only widths the original can fill, plus the original width itself.
  const widths = [...new Set([...WIDTHS.filter((w) => w < width), Math.min(width, 1920)])].sort((a, b) => a - b);

  for (const w of widths) {
    for (const [fmt, opts] of [["avif", { quality: 52, effort: 4 }], ["webp", { quality: 74 }]]) {
      const dest = path.join(out, `${id}-${w}.${fmt}`);
      if (await isFresh(src, dest)) continue;
      await sharp(src).rotate().resize({ width: w, withoutEnlargement: true })[fmt](opts).toFile(dest);
    }
  }

  // Tiny blurred preview used as the frame's background while the photo loads.
  const tiny = await sharp(src).rotate().resize(16).webp({ quality: 40 }).toBuffer();
  manifest[id] = {
    width,
    height,
    widths,
    blur: `data:image/webp;base64,${tiny.toString("base64")}`,
  };
}

// Open Graph / share image: the garden hero, 1200x630.
const og = path.join(root, "public", "og.jpg");
if (!(await isFresh(path.join(root, sources.jardin), og))) {
  await sharp(path.join(root, sources.jardin)).rotate()
    .resize(1200, 630, { fit: "cover", position: "centre" })
    .jpeg({ quality: 82, mozjpeg: true }).toFile(og);
}

const ts = `// Generated by scripts/optimize-images.mjs. Do not edit by hand.
export const photoManifest = ${JSON.stringify(manifest, null, 2)} as const;

export type PhotoId = keyof typeof photoManifest;
`;
await writeFile(path.join(root, "src", "data", "photos.generated.ts"), ts);
console.log(`images: ${Object.keys(manifest).length} photos ready in public/img`);
